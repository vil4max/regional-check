"""Turns the simplified geoBoundaries UKR ADM1 layer into the app's compact outline file.

Each unit gets the app's id (an `AlertRegion` raw value, or `crimea` / `sevastopol`) and its rings
projected into a box of width 1: equirectangular, longitude scaled by cos(48.4 deg), y downwards.
Usage: compact_outlines.py <simplified.geojson> <out.json> <out-aspect.swift>
"""

import json
import math
import sys

# geoBoundaries shapeID -> app id. Kyiv city and Kyiv Oblast share the name "Kyivska", so ids,
# not names, decide.
SHAPE_IDS = {
    "82583831B17032883652392": "crimea",
    "82583831B61774372920199": "vinnytsia",
    "82583831B8521204452203": "volyn",
    "82583831B96004676694065": "dnipropetrovsk",
    "82583831B94142902726322": "donetsk",
    "82583831B9589848299664": "zhytomyr",
    "82583831B18144742655321": "zakarpattia",
    "82583831B76074153455964": "zaporizhzhia",
    "82583831B79719181911578": "ivanoFrankivsk",
    "82583831B27908373306414": "kyivOblast",
    "82583831B10116413873639": "kirovohrad",
    "82583831B54873972991132": "luhansk",
    "82583831B29518876663819": "lviv",
    "82583831B18817350158740": "mykolaiv",
    "82583831B78920109116756": "odesa",
    "82583831B11695179874863": "poltava",
    "82583831B61452359234308": "rivne",
    "82583831B74892353494024": "sumy",
    "82583831B11810242945582": "ternopil",
    "82583831B2664207746433": "kharkiv",
    "82583831B11474817666067": "kherson",
    "82583831B88357083608746": "khmelnytskyi",
    "82583831B40882430166758": "cherkasy",
    "82583831B38832939133562": "chernivtsi",
    "82583831B87330598112957": "chernihiv",
    "82583831B38424722393808": "kyivCity",
    "82583831B98131377155256": "sevastopol",
}
# Drawn last, over the units that enclose them.
ON_TOP = ("kyivCity", "sevastopol")
MID_LATITUDE = 48.4


def rings_of(geometry):
    polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
    return [ring for polygon in polygons for ring in polygon]


def main(source, out_json, out_swift):
    features = json.load(open(source, encoding="utf-8"))["features"]
    units = {}
    for feature in features:
        shape_id = feature["properties"]["shapeID"]
        if shape_id not in SHAPE_IDS:
            sys.exit(f"unknown shapeID {shape_id}")
        units[SHAPE_IDS[shape_id]] = rings_of(feature["geometry"])
    if len(units) != len(SHAPE_IDS):
        sys.exit(f"expected {len(SHAPE_IDS)} units, got {len(units)}")

    scale = math.cos(math.radians(MID_LATITUDE))
    points = [(lon * scale, -lat) for rings in units.values() for ring in rings for lon, lat in ring]
    min_x = min(x for x, _ in points)
    min_y = min(y for _, y in points)
    width = max(x for x, _ in points) - min_x
    height = max(y for _, y in points) - min_y

    def project(ring):
        flat = []
        for lon, lat in ring[:-1]:  # GeoJSON repeats the first point; the path closes itself.
            flat += [round((lon * scale - min_x) / width, 4), round((-lat - min_y) / width, 4)]
        return flat

    order = sorted(units, key=lambda unit: (unit in ON_TOP, unit))
    out = {
        "source": "geoBoundaries gbHumanitarian UKR ADM1 (State Scientific Production Enterprise "
        "Kartographia, via OCHA HDX), CC BY 3.0 IGO",
        "units": [{"id": unit, "rings": [project(ring) for ring in units[unit]]} for unit in order],
    }
    with open(out_json, "w", encoding="utf-8") as handle:
        json.dump(out, handle, separators=(",", ":"))
        handle.write("\n")
    aspect = width / height
    with open(out_swift, "w", encoding="utf-8") as handle:
        handle.write(
            "// Generated by scripts/map/build-outlines.sh; do not edit.\n"
            "import CoreGraphics\n\n"
            "extension UkraineOutlines {\n"
            "    /// Width over height of the projected outlines, so layout never parses the data.\n"
            f"    static let aspectRatio: CGFloat = {aspect:.6f}\n"
            "}\n"
        )
    print(f"{len(units)} units, {sum(len(r) for u in units.values() for r in u)} rings, aspect {aspect:.6f}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
